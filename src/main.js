import './style.css';
const artwork = document.querySelector('#artwork');
const gallery = document.querySelector('.gallery');
const status = document.querySelector('#status');
const regenerate = document.querySelector('#regenerate');
const download = document.querySelector('#download');
const modes = [...document.querySelectorAll('[data-mode]')];
const paperDialog = document.querySelector('#paper-dialog');
const paintings = new Map();
let mode = 'flowers';
let busy = false;
let engine;
let timeout;
function setBusy(value, message = '') {
  busy = value;
  gallery.setAttribute('aria-busy', String(value));
  regenerate.disabled = value;
  download.disabled = value || !paintings.has(mode);
  for (const button of modes) button.disabled = value;
  status.textContent = message;
}
async function showPainting(painting) {
  artwork.className = `artwork ${painting.mode}`;
  artwork.style.backgroundImage = '';
  artwork.style.backgroundSize = '';
  const image = new Image();
  image.alt = painting.mode === 'flowers' ? 'Procedurally generated flower painting' : 'Procedurally generated Chinese landscape';
  if (painting.mode === 'flowers') {
    image.src = painting.png;
    await image.decode();
    artwork.replaceChildren(image);
  } else {
    // All SVG content is generated by the vendored engine, never user input.
    const svg = new DOMParser().parseFromString(painting.svg, 'image/svg+xml').documentElement;
    svg.setAttribute('role', 'img');
    svg.setAttribute('aria-label', image.alt);
    svg.style.mixBlendMode = 'multiply';
    artwork.style.backgroundImage = `url("${painting.texture}")`;
    artwork.style.backgroundSize = `${512 / painting.width * 100}% auto`;
    artwork.replaceChildren(document.importNode(svg, true));
  }
}
function generatePainting() {
  if (busy) return;
  setBusy(true, 'Making your painting…');
  engine?.remove();
  engine = document.createElement('iframe');
  engine.className = 'engine';
  engine.title = 'Painting generator';
  engine.setAttribute('aria-hidden', 'true');
  engine.tabIndex = -1;
  const seed = Date.now().toString(36) + '-' + crypto.getRandomValues(new Uint32Array(1))[0].toString(36);
  engine.src = `${import.meta.env.BASE_URL}engines/${mode}.html?seed=${seed}`;
  document.body.append(engine);
  timeout = setTimeout(() => {
    engine?.remove();
    setBusy(false, 'Generation took too long. Please try Regenerate.');
  }, 120_000);
}
window.addEventListener('message', async event => {
  if (event.origin !== location.origin || event.source !== engine?.contentWindow) return;
  if (!['painting-ready', 'painting-error'].includes(event.data?.type)) return;
  clearTimeout(timeout);
  if (event.data.type === 'painting-error') {
    engine.remove();
    setBusy(false, 'Could not make the painting. Please try Regenerate.');
    return;
  }
  try {
    const painting = event.data;
    if (painting.mode !== mode) throw new Error('Unexpected painting type');
    await showPainting(painting);
    paintings.set(mode, painting);
    engine.remove();
    setBusy(false);
  } catch (error) {
    console.error(error);
    engine?.remove();
    setBusy(false, 'Could not show the painting. Please try Regenerate.');
  }
});
regenerate.addEventListener('click', generatePainting);
for (const button of modes) {
  button.addEventListener('click', async () => {
    if (busy || mode === button.dataset.mode) return;
    mode = button.dataset.mode;
    for (const tab of modes) tab.setAttribute('aria-pressed', String(tab.dataset.mode === mode));
    artwork.className = `artwork ${mode}`;
    if (paintings.has(mode)) {
      setBusy(true);
      try { await showPainting(paintings.get(mode)); setBusy(false); }
      catch { setBusy(false, 'Could not show the painting. Please try Regenerate.'); }
    } else generatePainting();
  });
}
async function savePdf(paper = 'a4') {
  const painting = paintings.get(mode);
  if (busy || !painting) return;
  setBusy(true, 'Preparing your PDF…');
  try {
    const { downloadPainting } = await import('./pdf.js');
    await downloadPainting(painting, paper);
    setBusy(false);
  } catch (error) {
    console.error(error);
    setBusy(false, 'Could not download the PDF. Please try again.');
  }
}
download.addEventListener('click', () => {
  if (mode === 'flowers') savePdf();
  else { paperDialog.returnValue = ''; paperDialog.showModal(); }
});
paperDialog.addEventListener('close', () => {
  if (paperDialog.returnValue === 'download') savePdf(paperDialog.querySelector('input:checked').value);
});
paperDialog.addEventListener('click', event => {
  if (event.target !== paperDialog) return;
  const bounds = paperDialog.getBoundingClientRect();
  if (event.clientX < bounds.left || event.clientX > bounds.right || event.clientY < bounds.top || event.clientY > bounds.bottom) paperDialog.close('cancel');
});
generatePainting();
